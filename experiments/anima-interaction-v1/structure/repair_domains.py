"""T2c: repair-v2 LOCAL CONTACT-GROUP domains for anima-interaction-v1 R inputs.

Why this file exists (plan section 8.1 "R 接口修正"): T2b's mechanical audit
(checks/structure-render-verify.json risk1) proved render.py's support is the whole-body
binary union(owner_a, owner_b) dilated 48px — 10.3%-69.7% of canvas, median 43.1%, and
HAND-XH core=0 / support=69.2% — NOT a local contact-group edit domain. The old core is
owner-proximity only (pixels of A within 6px of B), not semantic contact. R must not consume
those domains. This program re-derives core/support/context (+ native structural-reference
gray) per case from the FROZEN action definitions, with NO change to frozen world poses /
cameras / character owners / pose / box:

  * parts: FK control-point capsules (frozen MHR rig FK via geometry_core.control_points) for the
    semantic body parts of the frozen contact group (frozen_poses.ACTION_TEMPLATES[*].contact_group):
      HAND  — both clasping wrists/palms + authored interlock finger joints + necessary forearms;
      HUG   — wrapping shoulders/arms + hands-on-back wrists + chest/back torso contact;
      KISS  — both heads/necks + documented lip proxies (head + 0.10*forward - 0.03*up);
      CARRY — A's load-bearing arms, B's thigh/knee support points + shins, B's hands on A's
              shoulders, B's pelvis seated on A's back (wide BY SEMANTIC LIST, not by coverage).
  * anchors: every part control and contact-pair endpoint is projected through the case's frozen
    camera with the FROZEN pose3d.project; px coordinates are recorded in the index (traceable;
    no generated image is ever looked at, no domain is chosen from model output).
  * core: part capsules intersected with the REAL rendered owner FULL silhouettes (T2b PNGs,
    sha256-verified against the rendered structure_index.json), UNIONED with screen-space bridge
    capsules spanning each frozen contact pair's gap, so the gap/seam that must be reconstructed
    between the two people is INSIDE the core. The core is never an owner intersection and never
    a whole-body union.
  * support: growth (support_grow_px) of the LOCAL contact-group seed only — never the whole body.
  * context: support dilated context_grow_px — independent context domain for Crop & Stitch.
  * gray: native STRUCTURAL REFERENCE only (same frozen falloff algorithm, ring 61px on 1024x768).
    The real crop-space noise gray (round(min(H,W)*0.08) Chebyshev ring) is regenerated by T4c
    YugangRepairMaskFalloff on the actual crop; no STITCHER scale is guessed here.

Selection: the 32 R core cases = 8 worlds x framings {W,M,C,XU}. XH never runs R (excluded);
solo cases have no contact (excluded). The old 416 PNGs / structure_index.json are READ-ONLY
inputs (hash-verified) and are never modified; outputs go to inputs/repair-v2/ only, and the
program refuses to run if --out resolves inside --structure.

Failure semantics: if a frozen contact pair projects INSIDE the frame but the derived core or
support is empty, that is a REAL failure — recorded per case, listed in the root index
"failures", non-zero exit. Never a mechanical skip. If the anchors project out of frame, the
recorded projection coordinates are the evidence and emptiness is a mechanical fact.

Coverage gate: every control named in the frozen contact_group.controls MUST appear in the
semantic part/pair list; a missing one aborts the run (no silent whole-body fallback).

Run (CPU only; numpy + Pillow; frozen RS geometry via rs_bridge; NO GPU, no sampling, no image
viewing — the real 32-case execution is dispatched separately):
  /usr/local/bin/python3 experiments/anima-interaction-v1/structure/repair_domains.py \
      --geometry experiments/anima-interaction-v1/structure/frozen/geometry.json \
      --structure var/local-driver/anima-interaction-v1/inputs/structure \
      --out var/local-driver/anima-interaction-v1/inputs/repair-v2
  # optional: --cases DC-HAND-W,DC-HUG-M   --dry-run (FK/projection plan + source hash check
  #           only; no mask decode, no domain raster, no PNG writes)
"""
