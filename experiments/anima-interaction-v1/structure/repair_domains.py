def _hand_parts(side: str) -> list:
    """Wrist/palm + the authored interlock finger joints + forearm (elbow->wrist)."""
    parts = [("point", f"{side}_wrist", "hand"),
             ("seg", f"{side}_elbow", f"{side}_wrist", "limb")]
    parts += [("point", f"{side}_{sfx}", "finger") for sfx in sorted(FP.FINGER_INTERLOCK)]
    return parts


def _arm_parts(side: str) -> list:
    """Shoulder -> elbow -> wrist chain + shoulder cap (wrapping / load-bearing arm)."""
