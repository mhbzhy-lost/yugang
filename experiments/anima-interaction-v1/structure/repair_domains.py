# ---------------------------------------------------------------------------
# Coverage gate: every frozen contact_group control must be covered by the semantic parts/pairs.
# ---------------------------------------------------------------------------
def group_anchor_names(group: dict) -> set:
    names = set()
    for slot, parts in group["parts"].items():
        for spec in parts:
            if spec[0] == "point":
                names.add(f"{slot}.{spec[1]}")
            else:
                names.add(f"{slot}.{spec[1]}")
                names.add(f"{slot}.{spec[2]}")
    for pr in group["pairs"]:
        names.add(pr["a"])
        names.add(pr["b"])
    return names


def check_frozen_coverage(action: str, group: dict) -> None:
    cg = FP.ACTION_TEMPLATES[action]["contact_group"]
    frozen = set(cg["controls"])
    covered = group_anchor_names(group)
    missing = sorted(frozen - covered)
    if missing:
        raise SystemExit(f"repair_domains.py: {action} group does not cover frozen contact_group "
                         f"controls {missing}; refusing to fall back to whole-body domains")
    if action == "HAND":
        inter = FP.ACTION_TEMPLATES["HAND"]["interlock_hands"]
        for slot, side in inter.items():
            fingers = [n for n in covered if n.startswith(f"{slot}.{side}_")
                       and any(sfx in n for sfx in FP.FINGER_INTERLOCK)]
            if len(fingers) != len(FP.FINGER_INTERLOCK):
                raise SystemExit(f"repair_domains.py: HAND {slot}.{side} covers {len(fingers)}/"
                                 f"{len(FP.FINGER_INTERLOCK)} interlock finger joints")


# ---------------------------------------------------------------------------
# Anchor projection (FROZEN pose3d.project through the case's frozen camera).
# ---------------------------------------------------------------------------
def anchor_world(name: str, cps_a: dict, cps_b: dict) -> np.ndarray:
    slot, ctrl = name.split(".", 1)
    cps = cps_a if slot == "A" else cps_b
    if ctrl == "lip_proxy":
        return G.lip_proxy(cps)
    if ctrl not in cps:
        raise KeyError(f"repair_domains.py: unknown MHR control in anchor {name}")
    return cps[ctrl]


def _cam_basis(camera: dict):
    pose3d = rs_bridge.pose3d()
    pos = np.array(camera["position"], float)
    tgt = np.array(camera["target"], float)
    fwd = tgt - pos
    fwd = fwd / np.linalg.norm(fwd)
    right = np.cross(np.array([0.0, 1.0, 0.0]), fwd)
    n = float(np.linalg.norm(right))
    right = right / n if n > 1e-6 else np.array([1.0, 0.0, 0.0])
    return pose3d, pos, fwd, right


def project_anchors(names, cps_a, cps_b, camera, w, h) -> dict:
    out = {}
    for name in sorted(names):
        wp = anchor_world(name, cps_a, cps_b)
        px = G.project_points([wp], camera, w, h)[0]
        in_frame = bool(px[2] > 0.05 and 0.0 <= px[0] < w and 0.0 <= px[1] < h)
        out[name] = {"world": [round(float(v), 4) for v in wp],
                     "px": [round(float(px[0]), 2), round(float(px[1]), 2)],
                     "depth": round(float(px[2]), 4), "in_frame": in_frame}
    return out


# ---------------------------------------------------------------------------
# Part capsule raster: perspective-scaled discs along frozen FK bone segments (same projection
# chain as render.py tail_pixels; NOT a re-implementation of the RS body rasterizer).
# ---------------------------------------------------------------------------
def _part_point(ctrl: str, cps: dict) -> np.ndarray:
    if ctrl == "lip_proxy":
        return G.lip_proxy(cps)
    return cps[ctrl]


def parts_capsule(parts, cps: dict, camera: dict, w: int, h: int) -> np.ndarray:
    from PIL import Image, ImageDraw
    pose3d, _pos, _fwd, right = _cam_basis(camera)
    img = Image.new("L", (w, h), 0)
    dr = ImageDraw.Draw(img)
    for spec in parts:
        if spec[0] == "point":
            segs = [(_part_point(spec[1], cps), None, RADII[spec[2]])]
        else:
            segs = [(_part_point(spec[1], cps), _part_point(spec[2], cps), RADII[spec[3]])]
        for p0, p1, r in segs:
            ts = [0.0] if p1 is None else [float(t) for t in np.linspace(0.0, 1.0, SEG_SAMPLES)]
            for t in ts:
                wp = p0 if p1 is None else p0 + t * (p1 - p0)
                cam = pose3d.camera_coordinates(np.array([wp]), camera)[0]
                if cam[2] <= 0.05:
                    continue
                px = G.project_points([wp, wp + right * r], camera, w, h)
                if (px[:, 2] <= 0.05).any():
                    continue
                rad = max(2.0, float(math.hypot(px[1, 0] - px[0, 0], px[1, 1] - px[0, 1])))
                dr.ellipse((px[0, 0] - rad, px[0, 1] - rad, px[0, 0] + rad, px[0, 1] + rad), fill=255)
    return np.asarray(img, dtype=np.uint8) > 0


def bridge_mask(pa_px, pb_px, radius_px: int) -> np.ndarray:
    """Screen-space capsule spanning one contact pair's gap (the seam that must be rebuilt)."""
    from PIL import Image, ImageDraw
    img = Image.new("L", (CANVAS_W, CANVAS_H), 0)
    dr = ImageDraw.Draw(img)
    pa = np.asarray(pa_px, float)
    pb = np.asarray(pb_px, float)
    dist = float(np.hypot(*(pb - pa)))
    n = max(2, int(math.ceil(dist / 2.0)))
    for i in range(n + 1):
        pt = pa + (pb - pa) * (i / n)
        dr.ellipse((pt[0] - radius_px, pt[1] - radius_px, pt[0] + radius_px, pt[1] + radius_px), fill=255)
    return np.asarray(img, dtype=np.uint8) > 0


def mask_stats(mask: np.ndarray, w: int, h: int) -> dict:
    ys, xs = np.nonzero(mask)
    if xs.size == 0:
        return {"pixels": 0, "empty": True, "pixel_bbox": None, "bbox_norm": None,
                "coverage_of_canvas": 0.0}
    box = G.box_normalize(float(xs.min()), float(ys.min()), float(xs.max()) + 1.0, float(ys.max()) + 1.0, w, h)
    return {"pixels": int(xs.size), "empty": False, "pixel_bbox": box["pixel_bbox"],
            "bbox_norm": {k: box[k] for k in ("x", "y", "width", "height")},
            "coverage_of_canvas": round(float(xs.size) / float(w * h), 6)}


# ---------------------------------------------------------------------------
# Source loading: real rendered owner masks, sha256-verified against the rendered structure index.
# ---------------------------------------------------------------------------
def load_source_mask(struct_entry: dict, key: str, repo_root: Path):
    f = struct_entry["files"][key]
    p = Path(f["path"])
    if not p.is_absolute():
        p = repo_root / p
    if not p.is_file():
        raise RuntimeError(f"rendered source mask missing: {key} at {p} (run T2b render.py first)")
    got = RN.sha256_file(p)
    if got != f["sha256"]:
        raise RuntimeError(f"source mask {key} sha256 mismatch: index {f['sha256']} != file {got} ({p})")
    from PIL import Image
    arr = np.asarray(Image.open(p).convert("L"), dtype=np.uint8)
    return arr > 127


def rel_to_repo(p, repo_root: Path) -> str:
    """Record index paths repo-root-relative, same shape as the rendered structure_index.json."""
    try:
        return str(Path(p).resolve().relative_to(repo_root.resolve()))
    except ValueError:
        return str(p)


# ---------------------------------------------------------------------------
# Per-case domain build.
# ---------------------------------------------------------------------------
def build_case(case: dict, geom: dict, struct_index: dict, repo_root: Path, out_root: Path,
               dry_run: bool = False) -> dict:
    case_id = case["case_id"]
    action = case["action"]
    group = GROUPS[action]
    check_frozen_coverage(action, group)
    scene = case["scene_json"]
    camera = scene["camera"]
    w, h = scene["width"], scene["height"]
    struct_entry = struct_index["cases"].get(case_id)
    if struct_entry is None:
        raise RuntimeError(f"case {case_id} missing from rendered structure_index.json")

    source_roles = {
        "scene.json": "consumed_readonly_equality_gate_vs_geometry",
        "owner_a.png": "provenance_recorded_visible_mask_not_consumed",
        "owner_b.png": "provenance_recorded_visible_mask_not_consumed",
        "owner_a_full.png": "consumed_readonly_part_body_intersection",
        "owner_b_full.png": "consumed_readonly_part_body_intersection",
    }
    sources = {
        "structure_index": {"path": str(repo_root / struct_index_path_rel(struct_index)),
                            "sha256": struct_index["_self_sha256"], "role": "consumed_readonly_index"},
    }
    for k, role in source_roles.items():
        f = struct_entry["files"][k]
        p = Path(f["path"])
        if not p.is_absolute():
            p = repo_root / p
        if not p.is_file():
            raise RuntimeError(f"rendered source file missing: {k} at {p} (run T2b render.py first)")
        got = RN.sha256_file(p)
        if got != f["sha256"]:
            raise RuntimeError(f"source {k} sha256 mismatch: index {f['sha256']} != file {got} ({p})")
        sources[k] = {"path": f["path"], "sha256": f["sha256"], "role": role}

    # Equality gate: the rendered scene.json must be byte-equal (as parsed JSON) to the frozen
    # geometry projection's scene_json — proves camera/people consumed here are the actually
    # rendered ones (no world/pose/owner drift between T2b assets and this derivation).
    scene_path = Path(sources["scene.json"]["path"])
    if not scene_path.is_absolute():
        scene_path = repo_root / scene_path
    rendered_scene = json.loads(scene_path.read_text(encoding="utf-8"))
    if rendered_scene != scene:
        raise RuntimeError(f"rendered {scene_path} != frozen geometry scene_json for {case_id}; "
                           "refusing to derive domains from drifted scene data")

    cps_a = G.control_points(scene["people"][0])
    cps_b = G.control_points(scene["people"][1])
    anchors = project_anchors(group_anchor_names(group), cps_a, cps_b, camera, w, h)

    pair_projection = []
    for pr in group["pairs"]:
        aa, ab = anchors[pr["a"]], anchors[pr["b"]]
        gap_world = float(np.linalg.norm(np.array(aa["world"]) - np.array(ab["world"])))
        gap_px = float(math.hypot(aa["px"][0] - ab["px"][0], aa["px"][1] - ab["px"][1]))
        pair_projection.append({"a": pr["a"], "b": pr["b"], "semantic": pr["semantic"],
                                "gap_world": round(gap_world, 4), "gap_px": round(gap_px, 2),
                                "both_in_frame": bool(aa["in_frame"] and ab["in_frame"])})
    expected_contact_in_frame = any(p["both_in_frame"] for p in pair_projection)
    out_of_frame_evidence = sorted(n for n, a in anchors.items() if not a["in_frame"])

    entry = {
        "case_id": case_id, "world_id": case["world_id"], "pair": case["pair"],
        "action": action, "framing": case["framing"],
        "status": "dry_run_planned",
        "sources": sources,
        "repair_params": dict(REPAIR_PARAMS),
        "group": {"kind": group["kind"], "semantic_source": group["semantic_source"],
                  "parts": {slot: [list(s) for s in parts] for slot, parts in group["parts"].items()},
                  "contact_pairs": group["pairs"]},
        "anchors": anchors,
        "contact_pair_projection": pair_projection,
        "expected_visible_contacts": case.get("expected_visible_contacts", []),
        "expected_contact_in_frame": expected_contact_in_frame,
        "out_of_frame_anchors": out_of_frame_evidence,
        "owner_mask_basis": "owner_*_full.png (complete silhouettes incl. mutually-occluded pixels): "
                            "in HUG/CARRY the contact limbs wrap BEHIND the partner, so their pixels "
                            "are absent from the visible masks; using visible-only would silently "
                            "shrink the wrapping-arm domains to ~nothing. Real T2b rendered files, "
                            "sha256-verified; consumed read-only.",
        "gray_note": "native gray.png is a STRUCTURAL REFERENCE only (frozen falloff algorithm, "
                     "ring 61px on 1024x768). The real crop-space noise gray "
                     "(round(min(H,W)*0.08) Chebyshev ring) is regenerated by T4c "
                     "YugangRepairMaskFalloff on the actual crop; no STITCHER scale is assumed here.",
    }

    cdir = out_root / case_id
    planned = [cdir / "repair_core.png", cdir / "support.png", cdir / "context.png",
               cdir / "gray.png", cdir / "repair_index.json"]
    if dry_run:
        entry["planned_files"] = [str(p) for p in planned]
        return entry

    owner_a_full = load_source_mask(struct_entry, "owner_a_full.png", repo_root)
    owner_b_full = load_source_mask(struct_entry, "owner_b_full.png", repo_root)

    capsule_a = parts_capsule(group["parts"]["A"], cps_a, camera, w, h)
    capsule_b = parts_capsule(group["parts"]["B"], cps_b, camera, w, h)
    cap_d = REPAIR_PARAMS["capsule_dilate_px"]
    part_body = ((G._box_dilate(capsule_a, cap_d) & owner_a_full)
                 | (G._box_dilate(capsule_b, cap_d) & owner_b_full))

    core_seed = part_body.copy()
    for pp in pair_projection:
        aa, ab = anchors[pp["a"]], anchors[pp["b"]]
        if pp["both_in_frame"]:
            core_seed |= bridge_mask(aa["px"], ab["px"], REPAIR_PARAMS["bridge_radius_px"])
        elif pp["gap_px"] <= REPAIR_PARAMS["bridge_radius_px"] * 4 and (aa["depth"] > 0.05 and ab["depth"] > 0.05):
            # Guard: an anchor slightly past the canvas edge (e.g. KISS C/XU heads clip the top
            # border while the lips stay in frame) must not silently drop the pair's seam from the
            # core. Bridge only when the two projections are near-adjacent and both in front of the
            # camera; the ellipse raster clips at the canvas border on its own.
            core_seed |= bridge_mask(aa["px"], ab["px"], REPAIR_PARAMS["bridge_radius_px"])
    core = G._box_dilate(core_seed, REPAIR_PARAMS["core_radius_px"])

    support_seed = core | (capsule_a & owner_a_full) | (capsule_b & owner_b_full)
    support = G._box_dilate(support_seed, REPAIR_PARAMS["support_grow_px"])
    context = G._box_dilate(support, REPAIR_PARAMS["context_grow_px"])
    gray = G.falloff_from_core(core, REPAIR_PARAMS["ring_px"], support)

    core_empty = bool(not core.any())
    support_empty = bool(not support.any())
    core_subset = bool(not np.any(core & ~support))
    failure = None
    if expected_contact_in_frame and (core_empty or support_empty):
        failure = ("REAL FAILURE: frozen contact pair projects inside the frame but the derived "
                   f"domain is empty (core_empty={core_empty}, support_empty={support_empty})")
    entry["status"] = "failed_domain_empty_expected_contact_in_frame" if failure else "rendered"
    entry["domains"] = {"core": mask_stats(core, w, h), "support": mask_stats(support, w, h),
                        "context": mask_stats(context, w, h)}
    entry["flags"] = {"core_empty": core_empty, "support_empty": support_empty,
                      "core_subset_of_support": core_subset, "failure": failure}
    if not core_subset:
        entry["flags"]["failure"] = (failure or "") + " REAL FAILURE: core not subset of support"
        entry["status"] = "failed_domain_empty_expected_contact_in_frame"

    cdir.mkdir(parents=True, exist_ok=True)
    files = {}
    files["repair_core.png"] = {"path": str(cdir / "repair_core.png"), "sha256": RN.save_mask(core, cdir / "repair_core.png")}
    files["support.png"] = {"path": str(cdir / "support.png"), "sha256": RN.save_mask(support, cdir / "support.png")}
    files["context.png"] = {"path": str(cdir / "context.png"), "sha256": RN.save_mask(context, cdir / "context.png")}
    files["gray.png"] = {"path": str(cdir / "gray.png"), "sha256": RN.save_gray(gray, cdir / "gray.png")}
    entry["canvas"] = [w, h]
    entry["files"] = files
    (cdir / "repair_index.json").write_text(json.dumps(entry, ensure_ascii=False, indent=1), encoding="utf-8")
    entry["files"]["repair_index.json"] = {"path": str(cdir / "repair_index.json"),
                                           "sha256": RN.sha256_file(cdir / "repair_index.json")}
    return entry


def struct_index_path_rel(struct_index: dict) -> str:
    return struct_index.get("_self_path_rel", "var/local-driver/anima-interaction-v1/inputs/structure/structure_index.json")


# ---------------------------------------------------------------------------
def main(argv=None):
    ap = argparse.ArgumentParser(
        description="T2c repair-v2: local contact-group core/support/context from frozen action "
                    "definitions + real rendered owner masks (CPU only; no GPU, no image viewing).")
    here = Path(__file__).resolve().parent
    repo = Path(os.environ.get("YUGANG_ROOT", here.parent.parent.parent))
    ap.add_argument("--geometry", default=str(here / "frozen" / "geometry.json"))
    ap.add_argument("--structure", default=str(repo / "var" / "local-driver" / "anima-interaction-v1" / "inputs" / "structure"))
    ap.add_argument("--out", default=str(repo / "var" / "local-driver" / "anima-interaction-v1" / "inputs" / "repair-v2"))
    ap.add_argument("--cases", default="", help="comma-separated case_id filter (default: the 32 R core cases)")
    ap.add_argument("--dry-run", action="store_true", help="FK/projection plan + source hash check; no masks, no PNGs")
    args = ap.parse_args(argv)

    geom_path = Path(args.geometry)
    struct_root = Path(args.structure)
    out_root = Path(args.out)
    # Guard: the old 416 PNGs / structure_index.json are read-only audit material.
    if out_root.resolve() == struct_root.resolve() or struct_root.resolve() in out_root.resolve().parents:
        raise SystemExit("repair_domains.py: --out must not live inside --structure; "
                         "old rendered assets are read-only")

    rs_bridge.load()  # verifies frozen RS geometry + real MHR asset before any FK/projection
    geom = json.loads(geom_path.read_text(encoding="utf-8"))
    geom_sha = RN.sha256_file(geom_path)
    struct_index_path = struct_root / "structure_index.json"
    if not struct_index_path.is_file():
        raise SystemExit(f"repair_domains.py: rendered {struct_index_path} missing (run T2b render.py first)")
    struct_index = json.loads(struct_index_path.read_text(encoding="utf-8"))
    struct_index["_self_sha256"] = RN.sha256_file(struct_index_path)
    try:
        struct_index["_self_path_rel"] = str(struct_index_path.relative_to(repo))
    except ValueError:
        struct_index["_self_path_rel"] = str(struct_index_path)

    # Case selection: 8 worlds x {W,M,C,XU} = the 32 R core cases. XH never runs R; solo has no contact.
    cases = [c for c in geom["projections"] if c["framing"] in R_FRAMINGS]
    want = set(x.strip() for x in args.cases.split(",") if x.strip())
    if want:
        cases = [c for c in cases if c["case_id"] in want]
        missing = want - {c["case_id"] for c in cases}
        if missing:
            raise SystemExit(f"repair_domains.py: unknown or non-R case_id(s): {sorted(missing)} "
                             f"(R consumes only framings {'/'.join(R_FRAMINGS)})")

    if not args.dry_run:
        out_root.mkdir(parents=True, exist_ok=True)

    index = {
        "schema": SCHEMA, "version": 1,
        "execution_state": "dry_run_planned" if args.dry_run else "rendered_cpu_no_gpu",
        "generated_by": "experiments/anima-interaction-v1/structure/repair_domains.py (T2c)",
        "supersedes": {
            "what": "inputs/structure/*/repair_core.png|support.png|context.png|gray.png whole-body "
                    "union domains (evidence: checks/structure-render-verify.json risk1)",
            "old_assets": "read-only audit material, NOT modified or overwritten",
        },
        "rs_commit": geom["rs_commit"], "rs_geometry_sha256": geom["rs_geometry_sha256"],
        "mhr_asset": geom["mhr_asset"], "canvas": geom["canvas"],
        "geometry_json": {"path": str(geom_path), "sha256": geom_sha},
        "repair_params": REPAIR_PARAMS,
        "part_radii_world_units": RADII,
        "part_radius_note": "world-unit FK-capsule radii; authoring proxies like "
                            "geometry_core.ENVELOPE_BODY_MARGIN, chosen from frozen MHR adult "
                            "proportions (~1.6u tall) and frozen contact residuals; NOT tuned "
                            "against any generated image",
        "case_selection": {"rule": "8 worlds x framings W/M/C/XU = 32 R core cases",
                           "xh_excluded": "R does not run XH (plan section 8.1)",
                           "solo_excluded": "no contact group", "count": len(cases)},
        "case_count": len(cases), "cases": {}, "failures": [],
    }
    for case in cases:
        try:
            entry = build_case(case, geom, struct_index, repo, out_root, dry_run=args.dry_run)
        except (RuntimeError, KeyError) as exc:
            entry = {"case_id": case["case_id"], "status": "failed_source_error",
                     "flags": {"failure": f"REAL FAILURE: {exc}"}}
        index["cases"][entry["case_id"]] = entry
        if entry.get("flags", {}).get("failure"):
            index["failures"].append({"case_id": entry["case_id"], "failure": entry["flags"]["failure"]})

    if not args.dry_run:
        (out_root / "repair_index.json").write_text(json.dumps(index, ensure_ascii=False, indent=1), encoding="utf-8")
    print(json.dumps({"out_root": str(out_root), "case_count": len(cases), "dry_run": args.dry_run,
                      "repair_index_written": not args.dry_run,
                      "failure_count": len(index["failures"]), "failures": index["failures"],
                      "repair_index": str(out_root / "repair_index.json")},
                     ensure_ascii=False, indent=2))
    return 1 if index["failures"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
